-- ---------------------------------------------------------------------------
-- history
-- ---------------------------------------------------------------------------
create table if not exists public.history (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users (id) on delete cascade,
  article_id bigint not null references public.articles (id) on delete cascade,
  opened_at  timestamptz not null default now()
);
create index if not exists history_user_idx on public.history (user_id, opened_at desc);

-- ---------------------------------------------------------------------------
-- search_logs (ringan, tanpa data sensitif yang tak perlu)
-- ---------------------------------------------------------------------------
create table if not exists public.search_logs (
  id           bigint generated by default as identity primary key,
  user_id      bigint references public.users (id) on delete set null,
  query        text not null,
  result_count integer not null default 0,
  created_at   timestamptz not null default now(),
  constraint search_logs_query_len check (char_length(query) <= 500),
  constraint search_logs_result_count_valid check (result_count >= 0)
);
create index if not exists search_logs_created_idx on public.search_logs (created_at desc);

-- ---------------------------------------------------------------------------
-- sync_logs
-- ---------------------------------------------------------------------------
create table if not exists public.sync_logs (
  id                bigint generated by default as identity primary key,
  started_at        timestamptz not null default now(),
  finished_at       timestamptz,
  articles_found    integer not null default 0,
  articles_inserted integer not null default 0,
  articles_updated  integer not null default 0,
  articles_failed   integer not null default 0,
  status            text not null default 'running',
  error_message     text,
  constraint sync_logs_status_check check (status in ('running', 'success', 'partial', 'failed')),
  constraint sync_logs_counts_valid check (
    articles_found >= 0 and articles_inserted >= 0 and
    articles_updated >= 0 and articles_failed >= 0
  )
);
create index if not exists sync_logs_started_idx on public.sync_logs (started_at desc);

-- ---------------------------------------------------------------------------
-- Trigger updated_at (articles)
