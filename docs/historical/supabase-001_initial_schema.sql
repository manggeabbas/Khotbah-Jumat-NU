-- ---------------------------------------------------------------------------
-- articles
-- ---------------------------------------------------------------------------
create table if not exists public.articles (
  id             bigint generated by default as identity primary key,
  title          text not null,
  slug           text,
  url            text not null,
  author         text,
  published_at   timestamptz,
  language       text default 'id',
  description    text,
  snippet        text,
  category       text,
  content        text,
  khutbah_1      text,
  khutbah_2      text,
  image_url      text,
  source         text not null default 'NU Online',
  content_hash   text,
  status         text not null default 'active',
  last_synced_at timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint articles_status_check check (status in ('active', 'parse_failed', 'archived')),
  constraint articles_url_not_blank check (length(btrim(url)) > 0)
);

-- Kolom yang mungkin belum ada pada instalasi lama (idempoten).
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'articles' and column_name = 'image_url'
  ) then
    alter table public.articles add column image_url text;
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'articles' and column_name = 'last_synced_at'
  ) then
    alter table public.articles add column last_synced_at timestamptz;
  end if;

  -- Kolom tsvector tergenerasi dengan pembobotan (judul > deskripsi/tag > isi).
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'articles' and column_name = 'search_vector'
  ) then
    alter table public.articles
      add column search_vector tsvector generated always as (
        setweight(to_tsvector('simple', coalesce(title, '')), 'A') ||
        setweight(to_tsvector('simple', coalesce(description, '')), 'B') ||
        setweight(to_tsvector('simple', coalesce(category, '')), 'B') ||
        setweight(to_tsvector('simple', coalesce(snippet, '')), 'C') ||
        setweight(to_tsvector('simple', coalesce(content, '')), 'C')
      ) stored;
  end if;
end $$;

-- UNIQUE url => mencegah duplikasi artikel oleh scraper.
create unique index if not exists articles_url_key on public.articles (url);
create index if not exists articles_published_at_idx on public.articles (published_at desc nulls last);
create index if not exists articles_status_idx on public.articles (status);
create index if not exists articles_content_hash_idx on public.articles (content_hash);
create index if not exists articles_search_vector_idx on public.articles using gin (search_vector);

