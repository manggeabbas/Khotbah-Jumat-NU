create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists articles_set_updated_at on public.articles;
create trigger articles_set_updated_at
  before update on public.articles
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Fungsi pencarian (FTS) — mengembalikan { total, items } sebagai JSONB.
-- ---------------------------------------------------------------------------
create or replace function public.search_articles(
  p_query  text,
  p_limit  integer default 8,
  p_offset integer default 0
)
returns jsonb
language sql
stable
as $$
  with q as (
    select websearch_to_tsquery('simple', p_query) as query
  ),
  matched as (
    select a.*, ts_rank(a.search_vector, q.query) as rank
    from public.articles a, q
    where a.status = 'active' and a.search_vector @@ q.query
  ),
  total as (select count(*)::int as n from matched),
  page as (
    select * from matched
    order by rank desc, published_at desc nulls last
    limit p_limit offset p_offset
  )
  select jsonb_build_object(
    'total', (select n from total),
    'items', coalesce((select jsonb_agg(to_jsonb(p)) from page p), '[]'::jsonb)
  );
$$;

-- ---------------------------------------------------------------------------
-- Keamanan (least privilege)
--
-- RLS diaktifkan pada SEMUA tabel. Backend memakai SUPABASE_SECRET_KEY yang
-- melewati (bypass) RLS, sehingga TIDAK ada API publik yang dibuka.
-- Tidak ada policy untuk `anon`/`authenticated` => akses publik ditolak.
--
-- Jika kelak butuh akses baca publik terbatas, tambahkan policy eksplisit
-- (mis. hanya kolom metadata artikel aktif) — jangan menonaktifkan RLS.
-- ---------------------------------------------------------------------------
alter table public.articles    enable row level security;
alter table public.users       enable row level security;
alter table public.favorites   enable row level security;
alter table public.history     enable row level security;
alter table public.search_logs enable row level security;
alter table public.sync_logs   enable row level security;

-- Pastikan tidak ada policy publik yang tertinggal dari versi lama.
drop policy if exists articles_public_read on public.articles;

-- ---------------------------------------------------------------------------
-- Privilese Data API (least privilege)
--
-- Peran API di project ini TIDAK otomatis mendapat DML (hanya Dxtm), sehingga
-- backend perlu GRANT eksplisit. Backend memakai satu-satunya peran tepercaya:
-- `service_role` (dipakai oleh SUPABASE_SECRET_KEY, dan bypass RLS).
-- `anon`/`authenticated` sengaja TIDAK diberi privilese apa pun.
-- ---------------------------------------------------------------------------
grant usage on schema public to service_role;
grant select, insert, update, delete on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;
